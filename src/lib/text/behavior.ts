/** 관찰 키워드와 평가단계로 행발(행동특성) 문장 초안 하나를 만든다. */
export const createBehaviorSentence = (keyword: string, degree: string, variant = 0) => {
  const stem = behaviorActionStems[keyword] ?? `${keyword}의 의미를 이해하고 바람직한 행동으로 실천`;
  const isEffort = /노력$/u.test(stem);
  const choices =
    degree === "잘함"
      ? [
          `${stem}하는 모습이 특히 돋보임.`,
          `${stem}하는 태도가 매우 바람직함.`,
          `${stem}하며 자신의 강점을 뚜렷하게 드러냄.`,
          `${stem}하는 능력이 우수함.`,
          `${stem}하는 자세가 인상적임.`,
          `${stem}하는 태도가 훌륭함.`,
          `${stem}하는 데 뛰어난 역량을 보임.`,
          `${stem}하는 자세를 잘 갖추고 있음.`,
          `${stem}하는 모습에서 강점이 잘 드러남.`,
          `${stem}하는 과정에서 뛰어난 능력을 발휘함.`,
          `${stem}하는 능력이 탁월함.`,
          `${stem}하는 태도에서 장점이 두드러짐.`,
        ]
      : degree === "노력요함"
        ? isEffort
          ? [
              `${stem}하는 태도를 꾸준히 이어감.`,
              `${stem}하는 경험을 쌓으며 점차 성장하고 있음.`,
              `${stem}하며 차근차근 실천함.`,
              `${stem}하는 자세가 바람직함.`,
              `${stem}하며 자신의 속도에 맞게 성장하고 있음.`,
              `${stem}하는 태도를 잃지 않고 이어감.`,
              `${stem}하는 과정에서 점차 발전함.`,
              `${stem}하며 꾸준히 경험을 넓혀 감.`,
              `${stem}하며 한 단계씩 발전하고 있음.`,
            ]
          : [
              `${stem}하려고 꾸준히 노력함.`,
              `${stem}하는 경험을 쌓으며 점차 성장하고 있음.`,
              `${stem}하기 위해 차근차근 실천함.`,
              `${stem}하려는 자세를 보임.`,
              `${stem}하는 과정에서 점차 발전하고 있음.`,
              `${stem}하는 태도를 기르기 위해 노력함.`,
              `${stem}하기 위해 꾸준히 실천함.`,
              `${stem}하려는 노력이 기특함.`,
              `${stem}하는 기회를 통해 조금씩 성장하고 있음.`,
              `${stem}하기 위해 차근차근 경험을 쌓고 있음.`,
            ]
        : [
            `${stem}함.`,
            `${stem}하는 태도가 바람직함.`,
            `${stem}하는 자세를 지님.`,
            `${stem}하는 모습을 보여 줌.`,
            `${stem}하는 능력을 갖추고 있음.`,
            `${stem}하는 태도가 자연스럽게 드러남.`,
            `${stem}하며 안정된 태도로 활동에 임함.`,
            `${stem}하는 자세가 잘 형성되어 있음.`,
            `${stem}하는 모습을 일관되게 보여 줌.`,
            `${stem}하는 과정이 인상적임.`,
            `${stem}하는 태도가 돋보임.`,
            `${stem}하는 역량을 충실히 발휘함.`,
          ];
  return choices[Math.abs(variant) % choices.length];
};

/** AI가 만든 행발 문장에 어색한 조사·메타 표현이 있는지 검사한다. */
export const hasAwkwardBehaviorMeta = (value: string) =>
  /(?:와|과)\s*관련한\s*관찰\s*내용|관련한\s*관찰\s*내용을\s*바탕으로|을\(를\)|모습을\s*(?:나타남|확인됨)|성장하는\s*모습을\s*두드러지게/u.test(
    value,
  );
